"""Reproducible, original synthetic data; no third-party download or redistribution."""
import argparse
import hashlib
import json
import random
from datetime import date, timedelta
from pathlib import Path
from sqlalchemy import select, func
from atlas import db

TABLES = [db.customers, db.products, db.variants, db.orders, db.shipments, db.returns]
CATEGORIES = ['shirt', 'trousers', 'dress', 'jacket', 'shoes', 'top', 'skirt', 'knitwear']


def generate(directory='data', seed=42, as_of=date(2026, 10, 26)):
    rng = random.Random(seed)
    root = Path(directory) / 'generated'
    root.mkdir(parents=True, exist_ok=True)
    customers = [dict(id=f'C{i:04}', name=f'Demo Customer {i}',
        tier='VIP' if i % 7 == 0 else 'standard', size=['M', 'S', 'L'][i % 3],
        style=['smart casual', 'formal', 'casual'][i % 3], country=['FR', 'DE', 'UK'][i % 3])
        for i in range(1, 201)]
    customers[0].update(size='M', style='smart casual')
    products = []
    variants = []
    for i in range(1, 121):
        category = CATEGORIES[(i-1) % len(CATEGORIES)]
        color = ['navy', 'cream', 'black', 'olive', 'blue'][i % 5]
        style = ['smart casual', 'formal', 'casual'][i % 3]
        products.append(dict(id=f'P{i:04}', name=f'Atlas {color.title()} {category.title()} {i:03}',
            category=category, style=style, color=color, price_cents=rng.choice([2900, 3900, 5900, 7900, 9900]),
            description=f'{color} {category} for {style} occasions. Original fictional Atlas catalog.'))
        for size in ['XS', 'S', 'M', 'L', 'XL']:
            variants.append(dict(id=f'P{i:04}-{size}', product_id=f'P{i:04}', size=size,
                stock=0 if (i + len(size)) % 9 == 0 else rng.randint(2, 40)))
    for product, price in zip(products[:3], [7900, 24900, 5900]):
        product['price_cents'] = price
    orders = []
    shipments = []
    for i in range(1, 601):
        pid = rng.randrange(120)
        age = rng.randint(2, 100)
        delivered = as_of - timedelta(days=age)
        status = 'delivered' if i % 5 else 'in_transit'
        orders.append(dict(id=f'O{1000+i}', customer_id=f'C{1+(i-1)//3:04}',
            variant_id=f'P{pid+1:04}-M', quantity=1, total_cents=products[pid]['price_cents'],
            purchased_at=(delivered-timedelta(days=4)).isoformat(),
            delivered_at=delivered.isoformat() if status == 'delivered' else None,
            status=status, condition='unworn', channel='online' if i % 2 else 'store'))
        shipments.append(dict(id=f'S{i:04}', order_id=f'O{1000+i}', status=status,
            estimated_delivery=(as_of+timedelta(days=2)).isoformat(), carrier='Atlas Mock Carrier'))
    # Scripted scenarios belong to C0001; O1004 belongs to C0002 (authorization test).
    orders[0].update(variant_id='P0001-M', purchased_at=(as_of-timedelta(days=14)).isoformat(), delivered_at=(as_of-timedelta(days=10)).isoformat(), total_cents=7900)
    orders[1].update(variant_id='P0002-M', purchased_at=(as_of-timedelta(days=9)).isoformat(), delivered_at=(as_of-timedelta(days=5)).isoformat(), total_cents=24900)
    orders[2].update(variant_id='P0003-M', purchased_at=(as_of-timedelta(days=59)).isoformat(), delivered_at=(as_of-timedelta(days=55)).isoformat(), total_cents=5900)
    orders[3].update(status='in_transit', delivered_at=None)
    shipments[3].update(status='delayed')
    returns = [dict(id=f'R{i:04}', order_id=f'O{1010+i*3}', reason='size', status='completed')
               for i in range(1, 61)]
    manifest = {'version':'1.0', 'seed':seed, 'as_of':as_of.isoformat(),
        'provenance':'Entirely generated by atlas.dataset; fictional names, catalog, policies, transactions.',
        'license':'CC0-1.0 for generated data and fictional policies', 'files':{}}
    for table, records in zip(TABLES, [customers, products, variants, orders, shipments, returns]):
        content = json.dumps(records, indent=2, sort_keys=True) + '\n'
        name = table.name + '.json'
        (root / name).write_text(content)
        manifest['files'][name] = {'rows':len(records), 'sha256':hashlib.sha256(content.encode()).hexdigest()}
    (root / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    return manifest


def seed(engine, directory='data'):
    root = Path(directory) / 'generated'
    if not (root / 'manifest.json').exists():
        generate(directory)
    manifest = json.loads((root / 'manifest.json').read_text())
    with engine.begin() as conn:
        if conn.scalar(select(func.count()).select_from(db.customers)):
            return
        for table in TABLES:
            raw = (root / (table.name+'.json')).read_bytes()
            expected = manifest['files'][table.name+'.json']
            if hashlib.sha256(raw).hexdigest() != expected['sha256']:
                raise ValueError(f'Dataset checksum failed: {table.name}')
            rows = json.loads(raw)
            if len(rows) != expected['rows']:
                raise ValueError('Dataset row count mismatch')
            conn.execute(table.insert(), rows)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--directory', default='data')
    parser.add_argument('--seed', type=int, default=42)
    args = parser.parse_args()
    print(json.dumps(generate(args.directory, args.seed), indent=2))
